"""Offline demo: synthetic injected-fraud evaluation, written to results/.

    PYTHONPATH=src python3 examples/run_synthetic_demo.py

All data is generated by ``checkout_anomaly.synthetic`` (no course data). The
numbers describe detection of the generator's own injected patterns only.
"""

from __future__ import annotations

import json
import platform
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from checkout_anomaly.evaluation import evaluate_synthetic, summarise  # noqa: E402

CONFIGS = {
    # the IF + K-Means distance ensemble of the original test1.py / 333 clean.py lineage
    "default_if_kmeans": {"detectors": ["isolation_forest", "kmeans_distance"], "seeds": [0, 1, 2, 3, 4]},
    # every scikit-learn detector ported from the lineage
    "all_sklearn_detectors": {"detectors": ["isolation_forest", "kmeans_distance", "mlp_autoencoder",
                                            "lof", "one_class_svm", "gmm"], "seeds": [0, 1, 2]},
}
PROTOCOL = {"n_train": 5000, "n_test": 1000, "train_fraud_rate": 0.02, "test_fraud_rate": 0.10,
            "contamination": 0.15, "k": 150}


def main() -> None:
    out_dir = ROOT / "results"
    out_dir.mkdir(exist_ok=True)
    report = {
        "label": "SYNTHETIC DATA ONLY - not a measurement on real shoppers or on the course data",
        "command": "PYTHONPATH=src python3 examples/run_synthetic_demo.py",
        "protocol": PROTOCOL,
        "environment": {"python": platform.python_version(), "numpy": np.__version__,
                        "pandas": pd.__version__, "scikit-learn": sklearn.__version__},
        "configs": {},
    }
    md = ["# Synthetic demo results", "",
          "**Synthetic data only.** Generated by `checkout_anomaly.synthetic`; the metrics measure how well",
          "the detectors find the generator's own injected patterns, not real-world fraud.", "",
          f"Command: `{report['command']}`  ",
          f"Protocol: {json.dumps(PROTOCOL)}  ",
          f"Environment: {json.dumps(report['environment'])}", ""]
    for name, cfg in CONFIGS.items():
        t0 = time.perf_counter()
        runs = [evaluate_synthetic(seed=s, detectors=cfg["detectors"], **PROTOCOL) for s in cfg["seeds"]]
        summary = summarise(runs)
        report["configs"][name] = {"detectors": cfg["detectors"], "seeds": cfg["seeds"], "runs": runs}
        cols = ["roc_auc", "average_precision", "precision_at_150", "recall_at_150",
                "auc_skipped_scan", "auc_under_priced", "auc_scan_pause"]
        table = summary[cols].xs("mean", axis=1, level=1).round(3)
        std = summary[cols].xs("std", axis=1, level=1).round(3)
        thr = pd.DataFrame([r["at_train_threshold"] for r in runs]).agg(["mean", "std"]).round(3)
        md += [f"## {name}", "", f"Detectors: {', '.join(cfg['detectors'])}; seeds: {cfg['seeds']}; "
               f"wall time {time.perf_counter() - t0:.0f} s", "",
               "Mean over seeds (test set: 1,000 visits, 10 % injected fraud, so 100 positives):", "",
               "```", table.to_string(), "```", "",
               "Standard deviation over seeds:", "",
               "```", std.to_string(), "```", "",
               "Ensemble at the threshold fitted on training scores (85th percentile of train):", "",
               "```", thr.to_string(), "```", ""]
        print(name, "\n", table.to_string(), "\n", thr.to_string(), flush=True)
    (out_dir / "synthetic_demo_metrics.json").write_text(json.dumps(report, indent=2))
    (out_dir / "synthetic_demo_summary.md").write_text("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
